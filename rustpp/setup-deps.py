#!/usr/bin/env python3
"""Rust++: prepare a checkout for building without contacting Rust's servers.

Everything the build needs from outside this repository was copied once into
the `deps-snapshot` release of the Rust++ GitHub repository:

  * the stage0 (bootstrap) compiler: rustc, rust-std and cargo tarballs,
  * the prebuilt LLVM ("rust-dev") matching `src/ci-llvm-sha`,
  * `vendor.tar.xz`: every crates.io dependency, vendored.

This script downloads those files from the snapshot release, verifies their
SHA-256 checksums, and puts them where bootstrap looks for them:

  build/cache/<stage0 date>/...                  stage0 tarballs
  build/cache/llvm-<target>-<sha>-false/...      prebuilt LLVM
  vendor/ + .cargo/config.toml                   vendored crates

It also writes a default `bootstrap.toml` if there is none.

Usage:  python3 rustpp/setup-deps.py [--target TRIPLE] [--ci]
Then:   python3 x.py build library
"""

import argparse
import hashlib
import os
import platform
import shutil
import sys
import tarfile
import urllib.request

DEFAULT_SNAPSHOT_URL = "https://github.com/AlzelemX/Rust-/releases/download/deps-snapshot"

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BOOTSTRAP_TOML = """\
# Generated by rustpp/setup-deps.py. Edit freely; the script won't overwrite it.
profile = "compiler"
change-id = "ignore"

[build]
# Use the crates in vendor/ instead of downloading from crates.io.
vendor = true
# The few submodules the build needs are already part of this repository.
submodules = false
compiler-docs = false

[rust]
debug-assertions = false
debug-logging = false
incremental = {incremental}

[llvm]
# Uses the LLVM tarball placed in build/cache by setup-deps.py.
download-ci-llvm = true
"""

CARGO_CONFIG = """\
# Generated by rustpp/setup-deps.py: build from vendored crates only.
[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor"
"""


def host_triple():
    machine = platform.machine().lower()
    arch = {"x86_64": "x86_64", "amd64": "x86_64", "aarch64": "aarch64", "arm64": "aarch64"}.get(machine)
    if sys.platform.startswith("win") and arch == "x86_64":
        return "x86_64-pc-windows-msvc"
    if sys.platform.startswith("linux") and arch:
        return arch + "-unknown-linux-gnu"
    if sys.platform == "darwin" and arch:
        return arch + "-apple-darwin"
    sys.exit("error: no snapshot for this OS/CPU; pass --target explicitly")


def read_stage0():
    data, checksums = {}, {}
    with open(os.path.join(ROOT, "src", "stage0"), encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            if key.startswith("dist/"):
                checksums[key.rsplit("/", 1)[1]] = value
            else:
                data[key] = value
    return data, checksums


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(base_url, name, dest_dir, expected_sha):
    os.makedirs(dest_dir, exist_ok=True)
    dest = os.path.join(dest_dir, name)
    if os.path.exists(dest) and sha256_of(dest) == expected_sha:
        print("ok (cached)  " + name)
        return dest
    url = base_url + "/" + name
    print("downloading  " + url)
    tmp = dest + ".part"
    with urllib.request.urlopen(url) as resp, open(tmp, "wb") as out:
        shutil.copyfileobj(resp, out, 1 << 20)
    actual = sha256_of(tmp)
    if actual != expected_sha:
        os.remove(tmp)
        sys.exit("error: checksum mismatch for {}: {} != {}".format(name, actual, expected_sha))
    os.replace(tmp, dest)
    return dest


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--target", default=None, help="host triple (default: detect)")
    parser.add_argument("--ci", action="store_true", help="CI settings (no incremental)")
    parser.add_argument(
        "--url",
        default=os.environ.get("RUSTPP_SNAPSHOT_URL", DEFAULT_SNAPSHOT_URL),
        help="base URL of the deps-snapshot release",
    )
    args = parser.parse_args()
    target = args.target or host_triple()

    stage0, stage0_sums = read_stage0()
    with open(os.path.join(ROOT, "src", "ci-llvm-sha"), encoding="utf-8") as f:
        llvm_sha = f.read().strip()

    # Checksums of the files that are not listed in src/stage0.
    sums_path = os.path.join(ROOT, "build", "cache", "rustpp-SHA256SUMS")
    os.makedirs(os.path.dirname(sums_path), exist_ok=True)
    with urllib.request.urlopen(args.url + "/SHA256SUMS") as resp:
        sums_text = resp.read().decode("utf-8")
    with open(sums_path, "w", encoding="utf-8") as f:
        f.write(sums_text)
    snapshot_sums = {}
    for line in sums_text.splitlines():
        parts = line.split()
        if len(parts) == 2:
            snapshot_sums[parts[1].lstrip("*")] = parts[0]

    # 1. stage0 compiler, where bootstrap.py expects its download cache.
    date, version = stage0["compiler_date"], stage0["compiler_version"]
    for component in ("rustc", "rust-std", "cargo"):
        name = "{}-{}-{}.tar.xz".format(component, version, target)
        fetch(args.url, name, os.path.join(ROOT, "build", "cache", date), stage0_sums[name])

    # 2. prebuilt LLVM, where bootstrap's ci-llvm download expects it.
    llvm_name = "rust-dev-nightly-{}.tar.xz".format(target)
    llvm_dir = os.path.join(ROOT, "build", "cache", "llvm-{}-{}-false".format(target, llvm_sha))
    fetch(args.url, llvm_name, llvm_dir, snapshot_sums[llvm_name])

    # 3. vendored crates.
    vendor_dir = os.path.join(ROOT, "vendor")
    if not os.path.isdir(vendor_dir):
        archive = fetch(
            args.url, "vendor.tar.xz", os.path.join(ROOT, "build", "cache"),
            snapshot_sums["vendor.tar.xz"],
        )
        print("extracting   vendor.tar.xz")
        with tarfile.open(archive, "r:xz") as tar:
            if hasattr(tarfile, "data_filter"):
                tar.extractall(ROOT, filter="data")
            else:
                tar.extractall(ROOT)
    else:
        print("ok (exists)  vendor/")

    cargo_config = os.path.join(ROOT, ".cargo", "config.toml")
    if not os.path.exists(cargo_config):
        os.makedirs(os.path.dirname(cargo_config), exist_ok=True)
        with open(cargo_config, "w", encoding="utf-8") as f:
            f.write(CARGO_CONFIG)
        print("wrote        .cargo/config.toml")

    bootstrap_toml = os.path.join(ROOT, "bootstrap.toml")
    if not os.path.exists(bootstrap_toml):
        with open(bootstrap_toml, "w", encoding="utf-8") as f:
            f.write(BOOTSTRAP_TOML.format(incremental="false" if args.ci else "true"))
        print("wrote        bootstrap.toml")

    print("\nDone. Build with:  python3 x.py build library")


if __name__ == "__main__":
    main()
